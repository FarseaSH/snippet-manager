import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';

const name = `__inline-style-${process.pid}`;
const file = path.resolve(process.env.SNIPPETS_DIR || 'snippets', `${name}.md`);
const source = '---\nsnippet_name: Inline Style\nsnippet_tags: []\n---\n\nMain `cmd --flag`.\n\n# Example\n\nSub `value`.\n\n````md\nPreview `hello 中文` and `' + 'long_'.repeat(40) + '`.\n\n```text\nnot inline\n```\n````';
test.beforeEach(async ({ context }) => {
  test.skip(process.env.APP_TEST_MODE === 'production');
  await context.grantPermissions(['clipboard-read', 'clipboard-write']);
  await fs.writeFile(file, source);
});
test.afterEach(async () => { await fs.rm(file, { force: true }); });
test('普通行内代码不预留图标空白，按住修饰键才增加图标空间，松开恢复', async ({ page }) => {
  await page.goto(`snippet/${name}`);
  const codes = page.locator('.inline-code-copy code:not(pre code)');
  const code = codes.first(), icon = code.locator('.inline-code-icon');
  await expect(codes).toHaveCount(4);
  await expect(icon).toHaveCSS('opacity', '0');
  await expect(code).toHaveCSS('padding-inline-end', '5px');
  await expect(codes.nth(2)).toHaveCSS('padding-inline-end', '6px');
  await expect(codes.nth(2)).toHaveCSS('background-color', 'rgb(233, 236, 239)');
  await expect(codes.nth(2)).toHaveCSS('border-top-width', '0px');
  const before = (await code.boundingBox())!;
  const background = await code.evaluate(node => getComputedStyle(node).backgroundColor);
  await page.mouse.move(5, 5);
  await page.keyboard.down('Control');
  await expect(code).toHaveCSS('color', 'rgb(194, 65, 12)');
  await expect(icon).toHaveCSS('opacity', '1');
  await expect(icon).toHaveAttribute('aria-hidden', 'true');
  const activated = (await code.boundingBox())!;
  expect(activated.width).toBeCloseTo(before.width + 16, 1);
  await expect(codes.nth(2)).toHaveCSS('padding-inline-end', '21px');
  await expect(codes.nth(2)).toHaveCSS('background-color', background);
  await expect(codes.nth(2)).toHaveCSS('border-top-width', '0px');
  await code.hover();
  await expect(code).toHaveCSS('color', 'rgb(154, 52, 18)');
  await expect(icon).toHaveCSS('color', 'rgb(154, 52, 18)');
  await expect(code).toHaveCSS('font-weight', '600');
  await expect(code).toHaveCSS('background-color', background);
  expect((await code.boundingBox())!.width).toBeCloseTo(activated.width, 1);
  const box = (await icon.boundingBox())!;
  await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2);
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('cmd --flag');
  await expect(page.locator('.inline-code-feedback')).toContainText('已复制');
  await expect(page.locator('pre .inline-code-icon')).toHaveCount(0);
  await page.keyboard.up('Control');
  await expect(icon).toHaveCSS('opacity', '0');
  await expect(code).toHaveCSS('padding-inline-end', '5px');
  await expect(codes.nth(2)).toHaveCSS('padding-inline-end', '6px');
  await expect(codes.nth(2)).toHaveCSS('background-color', 'rgb(233, 236, 239)');
  expect((await code.boundingBox())!.width).toBeCloseTo(before.width, 1);
  await page.setViewportSize({ width: 390, height: 900 });
  await page.goto(`snippet/${name}`);
  await expect(page.getByRole('region', { name: 'Markdown 预览', exact: true })).toBeVisible();
  await page.locator('.detail-drawer').evaluate(async node => { await Promise.all(node.getAnimations().map(animation => animation.finished)); });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.keyboard.down('Control');
  await page.screenshot({ path: 'test-results/inline-copy-mobile.png' });
  await page.keyboard.up('Control');
});
test('Mac 使用 ⌘ 激活灰色 Markdown 区域中的橙色复制提示，失焦复原', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(navigator, 'platform', { value: 'MacIntel' }));
  await page.goto(`snippet/${name}`);
  const code = page.locator('.markdown-preview-content p code').first();
  const icon = code.locator('.inline-code-icon');
  await expect(code).toHaveCSS('background-color', 'rgb(233, 236, 239)');
  await page.keyboard.down('Control'); await expect(icon).toHaveCSS('opacity', '1'); await page.keyboard.up('Control');
  await page.keyboard.down('Meta'); await expect(code).toHaveCSS('color', 'rgb(194, 65, 12)');
  await expect(code).toHaveCSS('background-color', 'rgb(255, 243, 232)');
  await code.click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('hello 中文');
  await page.evaluate(() => window.dispatchEvent(new Event('blur')));
  await expect(icon).toHaveCSS('opacity', '0');
  await expect(code).toHaveCSS('background-color', 'rgb(233, 236, 239)');
  await page.keyboard.up('Meta');
});
