test('转换右侧成功输出和转换源码支持复制，左侧编辑区、等待及错误状态不启用', async ({ page }) => {
  const code = 'export default function transform(input) { if (input === "error") throw Error("failed"); return { ok: true, output: input.toUpperCase() }; }';
  await fs.writeFile(file, '---\nsnippet_name: Copy Transform\nsnippet_tags: []\nsnippet_type: transform\n---\n\n```js\n' + code + '\n```');
  await page.goto(route);
  const mod = await shortcut(page);
  const inputRegion = page.getByRole('region', { name: '输入区', exact: true });
  const output = page.getByRole('region', { name: '输出区', exact: true });
  await page.keyboard.down(mod);
  await expect(page.locator('.code-copy-overlay.is-active')).toHaveCount(0);
  await page.keyboard.up(mod);
  await page.getByRole('textbox', { name: '转换输入', exact: true }).fill('hello');
  await expect(output.getByRole('button', { name: '复制结果' })).toBeEnabled();
  await page.keyboard.down(mod);
  await expect(inputRegion.locator('.code-copy-overlay')).toHaveCount(0);
  const overlay = page.locator('#transform-output .code-copy-overlay');
  await expect(overlay).toBeVisible();
  await overlay.click();
  await expect.poll(() => clipboard(page)).toBe('HELLO');
  await page.keyboard.up(mod);
  await page.getByRole('button', { name: '全屏输出', exact: true }).click();
  await page.keyboard.down(mod);
  await expect(overlay).toBeVisible();
  await overlay.click();
  await expect.poll(() => clipboard(page)).toBe('HELLO');
  await page.keyboard.up(mod);
  await page.keyboard.press('Escape');
  await page.getByRole('textbox', { name: '转换输入', exact: true }).fill('updated');
  await expect(output.getByRole('button', { name: '复制结果' })).toBeEnabled();
  await page.keyboard.down(mod);
  await overlay.click();
  await expect.poll(() => clipboard(page)).toBe('UPDATED');
  await page.keyboard.up(mod);
  await page.getByRole('textbox', { name: '转换输入', exact: true }).fill('error');
  await expect(page.locator('.transform-runtime-error')).toBeVisible();
  await page.keyboard.down(mod);
  await expect(page.locator('.code-copy-overlay.is-active')).toHaveCount(0);
  await page.keyboard.up(mod);
  await page.getByRole('tab', { name: '转换代码', exact: true }).click();
  await page.keyboard.down(mod);
  const source = page.getByRole('tabpanel', { name: '转换代码', exact: true }).locator('.code-copy-overlay');
  await expect(source).toBeVisible();
  await source.click();
  await expect.poll(() => clipboard(page)).toBe(code);
  await page.keyboard.up(mod);
});

test('窄屏降级代码支持外接键盘快捷复制，滚动时遮罩固定在可见代码区', async ({ page }) => {
  const code = Array.from({ length: 180 }, (_, index) => `line-${index} 中文`).join('\n');
  await fs.writeFile(file, snippet([['Example', 'text', code]]));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(route);
  await expect(page.getByRole('dialog', { name: '片段详情', exact: true })).toHaveCSS('transform', 'none');
  const fallback = page.locator('.code-fallback');
  await fallback.evaluate(node => { node.scrollTop = node.scrollHeight; });
  const mod = await shortcut(page);
  await page.keyboard.down(mod);
  const overlay = page.locator('.code-copy-overlay');
  await expect(overlay).toBeInViewport();
  const before = await overlay.boundingBox();
  await fallback.evaluate(node => { node.scrollTop = 0; });
  expect((await overlay.boundingBox())!.y).toBe(before!.y);
  await overlay.click();
  await expect.poll(() => clipboard(page)).toBe(code);
  await page.keyboard.up(mod);
});

test('复制失败显示提示并允许重试，松开修饰键立即恢复代码交互', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(navigator.clipboard, 'writeText', { configurable: true, value: () => Promise.reject(Error('denied')) });
    document.execCommand = () => false;
  });
  await fs.writeFile(file, snippet([['Example', 'text', 'retry code']]));
  await page.goto(route);
  const mod = await shortcut(page);
  await page.keyboard.down(mod);
  const overlay = page.locator('.code-copy-overlay');
  await expect(overlay).toBeVisible();
  await overlay.click();
  await expect(overlay).toContainText('复制失败，请重试');
  await page.keyboard.up(mod);
  await expect(overlay).toBeHidden();
  await page.evaluate(() => Reflect.deleteProperty(navigator.clipboard, 'writeText'));
  await page.keyboard.down(mod);
  await expect(overlay).toContainText('单击复制代码');
  await overlay.click();
  await expect.poll(() => clipboard(page)).toBe('retry code');
  await expect(overlay).toContainText('已复制代码');
  await page.keyboard.up(mod);
});
